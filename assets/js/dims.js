// =============================================================
//  dims.js ― d 次元の単原子理想気体の式（DOM 非依存）
//    シミュレーションは 2次元（d = 2）。「3次元なら」の比較表示（03・06・08）で
//    同じ式に d = 3 を入れた値を並べるために使う。粒子の計算はしない（式だけ）。
//    k = 1。1粒子あたりの自由度は d なので U = (d/2)NkT。
// =============================================================

/** 1粒子あたりの量：cv = d/2、cp = cv + 1（マイヤーの関係）、γ = cp/cv、温位の指数 k/cp */
export function idealGas(d) {
  const cv = d / 2, cp = cv + 1;
  return { d, cv, cp, gamma: cp / cv, kcp: 1 / cp };
}

/** 準静的・断熱に体積を V0 → V にしたときの温度（T V^{2/d} = 一定） */
export const adiabatT = (d, T0, V0, V) => T0 * (V0 / V) ** (2 / d);

/** 準静的・断熱に体積を V0 → V にしたときの圧力（P V^γ = 一定、γ = 1 + 2/d） */
export const adiabatP = (d, P0, V0, V) => P0 * (V0 / V) ** (1 + 2 / d);

/** 断熱膨張で温度を Th → Tc に下げるのに必要な体積比 (Th/Tc)^{d/2} */
export const adiabatVolumeRatio = (d, Th, Tc) => (Th / Tc) ** (d / 2);
